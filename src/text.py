"""Форматирование текста для аналитика. Владелец: kuanyshs.

Всё, что жюри читает глазами — evidence, why, гипотезы кластеров — проходит
через эти две функции. «3 платежей прошли» и «0.0 млн» выглядят как черновик
и подрывают доверие к числам рядом.
"""


def plural(n: int, one: str, few: str, many: str) -> str:
    """Русское склонение числительных: 1 платёж, 2 платежа, 5 платежей."""
    n = abs(int(n)) % 100
    if 11 <= n <= 14:
        return many
    n %= 10
    if n == 1:
        return one
    if 2 <= n <= 4:
        return few
    return many


def kzt(v: float) -> str:
    """Суммы читаемо: миллионы для крупных, тысячи для мелких.

    Единый формат «0.0 млн» превращал мелкие суммы в ноль и делал evidence
    бесполезным именно там, где узел мелкий и объяснение особенно нужно.
    """
    v = float(v)
    if abs(v) >= 1e6:
        return f"{v / 1e6:.1f} млн"
    if abs(v) >= 1e3:
        return f"{v / 1e3:.0f} тыс"
    return f"{v:.0f}"


def payers(n: int) -> str:
    return f"{n} {plural(n, 'плательщика', 'плательщиков', 'плательщиков')}"


def receivers(n: int) -> str:
    return f"{n} {plural(n, 'получателя', 'получателей', 'получателей')}"


def nodes(n: int) -> str:
    return f"{n} {plural(n, 'узел', 'узла', 'узлов')}"
